"""Create a local admin account and a demo user with sample history.

    python -m backend.scripts.seed_demo

The demo user's meal logs, likes and saved plan are SAMPLE DATA generated by the app's
own planner from real recipes in MySQL (so the dashboard has something to show). They
are not real eating records. Passwords come from SEED_ADMIN_PASSWORD and
SEED_DEMO_PASSWORD if set; otherwise the local-only defaults below are used.
"""

from __future__ import annotations

import os
import random
from datetime import date, timedelta

from backend.app import db
from backend.app.routers.planner import narrative
from backend.app.routers.profile import ProfileIn, save_profile
from backend.app.routers.recommend import log_recommendations
from backend.app.security import hash_password
from backend.app.services import planner
from backend.app.services.engine import engine
from backend.app.services.users import base_constraints, get_profile, user_state
from nutrimate_core import constraints as cons
from nutrimate_core import targets as tg

ADMIN_EMAIL = "admin@example.com"
DEMO_EMAIL = "demo@example.com"


def ensure_user(t, email, name, password, role="user") -> int:
    row = t.one("SELECT id FROM users WHERE email = %s", (email,))
    if row:
        t.run("UPDATE users SET password_hash = %s, role = %s WHERE id = %s", (hash_password(password), role, row["id"]))
        return row["id"]
    uid = t.run("INSERT INTO users (email, password_hash, full_name, role, onboarded) VALUES (%s,%s,%s,%s,1)",
                (email, hash_password(password), name, role))
    return uid


def main():
    db.init_schema()
    engine.load()
    rng = random.Random(7)
    admin_pw = os.environ.get("SEED_ADMIN_PASSWORD", "admin12345")
    demo_pw = os.environ.get("SEED_DEMO_PASSWORD", "demo12345")
    with db.tx() as t:
        admin_id = ensure_user(t, ADMIN_EMAIL, "NutriMate Admin", admin_pw, "admin")
        save_profile(t, admin_id, ProfileIn(diet="any", calorie_target=2200, protein_target_g=90, carbs_target_g=270,
                                            fat_target_g=70, fiber_target_g=30))
        t.run("UPDATE users SET onboarded = 1 WHERE id = %s", (admin_id,))

        uid = ensure_user(t, DEMO_EMAIL, "Demo User", demo_pw)
        for table in ("meal_logs", "meal_plans", "interactions", "recommendation_logs", "chat_messages",
                      "profile_history"):
            t.run(f"DELETE FROM {table} WHERE user_id = %s", (uid,))
        est = tg.estimate("male", 21, 172, 68, "moderate", "maintain")
        save_profile(t, uid, ProfileIn(sex="male", age=21, height_cm=172, weight_kg=68, activity="moderate",
                                       goal="maintain", diet="vegetarian", allergies=["peanut"],
                                       restrictions=["mushroom"], cuisines=["Indian", "Mexican"],
                                       calorie_target=est["daily_kcal"], protein_target_g=est["daily_protein_g"],
                                       carbs_target_g=est["daily_carbs_g"], fat_target_g=est["daily_fat_g"],
                                       fiber_target_g=30, meals_per_day=3))
        t.run("UPDATE users SET onboarded = 1 WHERE id = %s", (uid,))
        profile = get_profile(t, uid)
        c = base_constraints(profile)

        likes = t.all("""SELECT recipe_id, name, ingredients, instructions FROM recipes
                         WHERE is_vegetarian = 1 AND cuisine = 'Indian' AND meal_type IN ('main', 'side')
                         AND in_cf_data = 1 ORDER BY n_ratings DESC, recipe_id LIMIT 30""")
        liked = [r["recipe_id"] for r in likes if not cons.check_recipe(
            {**r, "calories_kcal": None, "protein_g": None, "total_minutes": None, "meal_type": "main",
             "cuisine": "Indian", "search_text": cons.recipe_text(r["name"], r["ingredients"], r["instructions"])},
            cons.Constraints(diet="vegetarian", exclude=c.exclude))][:8]
        for rid in liked:
            t.run("INSERT INTO interactions (user_id, item_type, item_id, action) VALUES (%s,'recipe',%s,'like')",
                  (uid, str(rid)))
        disliked = t.all("""SELECT recipe_id FROM recipes WHERE is_vegetarian = 1 AND meal_type = 'dessert'
                            ORDER BY n_ratings DESC LIMIT 2""")
        for r in disliked:
            t.run("INSERT INTO interactions (user_id, item_type, item_id, action) VALUES (%s,'recipe',%s,'dislike')",
                  (uid, str(r["recipe_id"])))

        state = user_state(t, uid, profile)
        kcal, protein = float(profile["calorie_target"]), float(profile["protein_target_g"])
        today = date.today()
        # two generated weeks give 14 different days; portions are varied a little per day
        history = planner.generate(state, c, kcal * 0.97, protein, 7, 3, today)["days"]
        history += planner.generate(state, c, kcal * 1.02, protein, 7, 3, today)["days"]
        for back in range(13, -1, -1):
            day = today - timedelta(days=back)
            if back in (9, 4):  # a couple of days without logging, as in real use
                continue
            meals = history[13 - back]["meals"]
            if back == 0:
                meals = meals[:2]  # today: breakfast and lunch so far
            for m in meals:
                servings = max(0.5, m["servings"] + rng.choice([-0.25, 0, 0, 0.25]))
                nut = planner.item_nutrition(m["recipe"], servings)
                t.run("""INSERT INTO meal_logs (user_id, log_date, slot, item_type, item_id, item_name, quantity, unit,
                         calories_kcal, protein_g, carbs_g, fat_g, fiber_g)
                         VALUES (%s,%s,%s,'recipe',%s,%s,%s,'serving',%s,%s,%s,%s,%s)""",
                      (uid, day, m["slot"], str(m["recipe"]["recipe_id"]), m["recipe"]["name"], servings,
                       *[nut[k] for k in planner.KEYS]))

        week = planner.generate(state, c, kcal, protein, 7, 3, today)
        week["narrative"], week["narrative_mode"], _ = narrative(week)
        pid = t.run("""INSERT INTO meal_plans (user_id, name, start_date, days, targets, summary, narrative, narrative_mode)
                       VALUES (%s,%s,%s,%s,%s,%s,%s,%s)""",
                    (uid, "Weekly vegetarian plan", today, 7, db.dumps({"calories_kcal": kcal, "protein_g": protein}),
                     db.dumps(week["summary"]), week["narrative"], week["narrative_mode"]))
        t.many("""INSERT INTO meal_plan_items (plan_id, day_index, slot, recipe_id, servings, nutrition)
                  VALUES (%s,%s,%s,%s,%s,%s)""",
               [(pid, d["day_index"], m["slot"], m["recipe"]["recipe_id"], m["servings"], db.dumps(m["nutrition"]))
                for d in week["days"] for m in d["meals"]])

        res = engine.recommend(state, c, k=12)
        log_recommendations(t, uid, "recommendations", {"constraints": c.describe(), "request": {}}, res)
    print(f"admin: {ADMIN_EMAIL}  demo: {DEMO_EMAIL}  (passwords from env or the defaults in this script)")
    print(f"demo user: {len(liked)} likes, 12 days of sample meal logs, 1 saved weekly plan")


if __name__ == "__main__":
    main()
